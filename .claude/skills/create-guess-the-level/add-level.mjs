#!/usr/bin/env node
/**
 * Add one Guess The level (question) to a category.
 *
 *   node .claude/skills/create-guess-the-level/add-level.mjs <category> "<answer>" \
 *       [--accept "<alias>"]... [--credit "<attribution>"]... [--keyframe <image>]... <clue>...
 *
 * <clue> (1–5, shown in this order) is one of:
 *   https://…/file        web image or video: DOWNLOADED and stored locally (the URL itself could leak the answer)
 *   path/to/file          local image or video, copied in
 *   <video>@<start>-<end> a video trimmed to that span in seconds, e.g. clip.mp4@2-6.5
 *   "emoji:🍕"            Twemoji SVG for that emoji (credit added automatically)
 *   "text:Some words"     plain text clue card (SVG); 1–2 characters ("text:A") render as a big letter
 *   "gen-image:<prompt>"  generated by the local image API at 512×512 (Qwen Image, ~15 s)
 *   "gen-video:<prompt>"  generated by the local video API at 480p, square (640×640), used as-is (MiniMax H3, 1–5 min);
 *                         --keyframe images pin its frames (centre-cropped to square first)
 *
 * Videos (and GIFs) become silent, metadata-free H.264 MP4s (≤1280px, faststart). A contact sheet of
 * frames is written to the temp folder for review. JPEG/PNG text metadata is stripped.
 * Every clue ends up at public/games/guess-the/<category>/<id>-<n>.<ext>.
 *
 * Options: --video-seconds N (gen-video length, default 4) · --dry-run (fetch, generate and check, write nothing).
 * Generated clues are also saved to the temp folder, so after a dry run you can pass those files instead of regenerating.
 * Env: IMAGE_API_URL (default http://localhost:8000), IMAGE_API_KEY.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import http from 'node:http';
import { tmpdir } from 'node:os';
import { extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '../../..');
const gameDir = join(root, 'src/games/guess-the');
const UA = 'PartyGamesLevels/1.0 (https://partygames.datasparta.com)';
const TWEMOJI = 'https://cdn.jsdelivr.net/npm/@twemoji/svg@15.0.0';
const TWEMOJI_CREDIT = 'Emoji: Twemoji (CC BY 4.0)';
const API = (process.env.IMAGE_API_URL ?? 'http://localhost:8000').replace(/\/$/, '');
const NO_TEXT = ' No text, letters, numbers, captions, signs, logos or watermarks anywhere.';
const IMAGE_BY_MIME = { 'image/jpeg': '.jpg', 'image/png': '.png', 'image/webp': '.webp', 'image/svg+xml': '.svg', 'image/avif': '.avif' };
const VIDEO_BY_MIME = { 'video/mp4': '.mp4', 'video/webm': '.webm', 'video/quicktime': '.mov', 'video/x-matroska': '.mkv', 'image/gif': '.gif', 'application/ogg': '.ogv', 'video/ogg': '.ogv' };
const IMAGE_EXT = new Set([...Object.values(IMAGE_BY_MIME), '.jpeg']);
const VIDEO_EXT = new Set([...Object.values(VIDEO_BY_MIME), '.m4v']);
const WARN_IMAGE = 400 * 1024;
const WARN_VIDEO = 3 * 1024 * 1024;
const work = mkdtempSync(join(tmpdir(), 'guess-the-'));
/** Generated images are 512×512. Generated videos are square at the API's 480p (640×640) and kept at that size. */
const GEN_SIZE = 512;
const BOX = 'scale=1280:720:force_original_aspect_ratio=decrease:force_divisible_by=2:flags=lanczos';
const SQUARE = `crop='min(iw,ih)':'min(iw,ih)',scale=${GEN_SIZE}:${GEN_SIZE}:flags=lanczos`;

function fail(msg) {
    console.error(`✗ ${msg}`);
    process.exit(1);
}

// ---- args ----
const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const accept = [];
const credits = [];
const keyframes = [];
let videoSeconds = 4;
const rest = [];
for (let i = 0; i < args.length; i++) {
    if (args[i] === '--dry-run') continue;
    else if (args[i] === '--accept') accept.push(args[++i] ?? fail('--accept needs a value'));
    else if (args[i] === '--credit') credits.push(args[++i] ?? fail('--credit needs a value'));
    else if (args[i] === '--keyframe') keyframes.push(args[++i] ?? fail('--keyframe needs a value'));
    else if (args[i] === '--video-seconds') videoSeconds = Number(args[++i]);
    else rest.push(args[i]);
}
const [category, answer, ...clues] = rest;
if (!category || !answer) fail('Usage: add-level.mjs <category> "<answer>" [--accept "<alias>"]... [--credit "<text>"]... <clue>...');
if (!(videoSeconds >= 1 && videoSeconds <= 10)) fail('--video-seconds must be 1–10');
if (keyframes.length > 4) fail('At most 4 --keyframe images');

// ---- category ----
const categoriesSrc = readFileSync(join(gameDir, 'categories.ts'), 'utf8');
const known = [...categoriesSrc.matchAll(/id:\s*'([^']+)'/g)].map(m => m[1]);
if (!known.includes(category)) fail(`Unknown category "${category}". Known: ${known.join(', ')}. Add new categories to categories.ts first.`);
const file = join(gameDir, 'content', `guess-the-${category}.json`);
const data = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : { questions: [] };

// ---- answer checks (same normalisation idea as mechanics/answers.ts) ----
const norm = s => s.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/['’`]/g, '').replace(/&/g, ' and ').replace(/[^\p{L}\p{N}]+/gu, ' ').trim().replace(/^(the|a|an) /, '');
if (!norm(answer)) fail('Answer is empty');
const dupe = data.questions.find(q => [q.answer, ...(q.accept ?? [])].some(a => norm(a) === norm(answer)));
if (dupe) fail(`"${answer}" already exists in ${category} as ${dupe.id}`);
if (clues.length < 1 || clues.length > 5) fail(`Give 1 to 5 clues (got ${clues.length})`);

const secrets = [answer, ...accept].map(a => norm(a).replace(/ /g, '')).filter(s => s.length > 3);
const leaks = text => secrets.some(s => norm(text).replace(/ /g, '').includes(s));

// ---- id: keep the file's prefix, next number ----
const ids = data.questions.map(q => q.id);
const prefix = ids[0]?.match(/^[a-z]+/)?.[0] ?? category[0];
const next = Math.max(0, ...ids.map(id => Number(id.match(/\d+$/)?.[0] ?? 0))) + 1;
const id = `${prefix}${next}`;

// ---- helpers ----
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function textCard(text) {
    const chars = [...text].length;
    const size = chars <= 2 ? 300 : text.length > 18 ? 52 : text.length > 10 ? 68 : 96;
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600" width="800" height="600">
<rect width="800" height="600" fill="#F5F2EC"/>
<text x="400" y="${chars <= 2 ? 330 : 310}" text-anchor="middle" dominant-baseline="middle" font-family="Geist, system-ui, sans-serif" font-size="${size}" font-weight="600" fill="#1A1814">${esc(text)}</text>
</svg>
`;
}

/** Twemoji file name: lowercase hex code points joined by "-", FE0F dropped unless it's a ZWJ sequence. */
function twemojiName(emoji) {
    const cps = [...emoji].map(c => c.codePointAt(0).toString(16));
    return (cps.includes('200d') ? cps : cps.filter(cp => cp !== 'fe0f')).join('-');
}

async function download(url, n) {
    const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'image/*,video/*' }, redirect: 'follow' });
    if (!res.ok) fail(`Clue ${n}: ${url} → HTTP ${res.status}`);
    const mime = (res.headers.get('content-type') ?? '').split(';')[0].trim();
    const ext = IMAGE_BY_MIME[mime] ?? VIDEO_BY_MIME[mime];
    if (!ext) fail(`Clue ${n}: ${url} is not an image or video (${mime || 'no content-type'}). Use the direct file URL, not the page.`);
    return { bytes: Buffer.from(await res.arrayBuffer()), ext };
}

function ffmpeg(argv, what) {
    const r = spawnSync('ffmpeg', ['-hide_banner', '-v', 'error', '-y', ...argv], { encoding: 'utf8' });
    if (r.error) fail(`${what}: ffmpeg not found. Install it (winget install ffmpeg) and retry.`);
    if (r.status !== 0) fail(`${what}: ffmpeg failed: ${r.stderr.trim().split('\n').slice(-3).join(' ')}`);
}

function probeSeconds(path) {
    const r = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path], { encoding: 'utf8' });
    return Number(r.stdout.trim()) || 0;
}

/**
 * Drop text metadata that can name the subject (photo titles, captions, keywords).
 * JPEG: APP1 (EXIF/XMP), APP13 (IPTC) and comments. PNG: tEXt/iTXt/zTXt/eXIf chunks.
 */
function stripMetadata(bytes, ext) {
    if (ext === '.jpg' && bytes[0] === 0xff && bytes[1] === 0xd8) {
        const out = [bytes.subarray(0, 2)];
        let i = 2;
        while (i + 4 <= bytes.length && bytes[i] === 0xff) {
            const marker = bytes[i + 1];
            if (marker === 0xda) break; // start of scan: image data follows
            const len = bytes.readUInt16BE(i + 2);
            if (marker !== 0xe1 && marker !== 0xed && marker !== 0xfe) out.push(bytes.subarray(i, i + 2 + len));
            i += 2 + len;
        }
        out.push(bytes.subarray(i));
        return Buffer.concat(out);
    }
    if (ext === '.png' && bytes.readUInt32BE(0) === 0x89504e47) {
        const out = [bytes.subarray(0, 8)];
        for (let i = 8; i + 12 <= bytes.length; ) {
            const len = bytes.readUInt32BE(i);
            const type = bytes.toString('latin1', i + 4, i + 8);
            if (!['tEXt', 'iTXt', 'zTXt', 'eXIf'].includes(type)) out.push(bytes.subarray(i, i + 12 + len));
            i += 12 + len;
        }
        return Buffer.concat(out);
    }
    return bytes;
}

/** Big photos and generated PNGs → JPEG ≤1280px (ffmpeg writes no metadata with -map_metadata -1). */
function shrinkImage(bytes, ext, n) {
    if (!['.jpg', '.png', '.webp'].includes(ext) || bytes.length <= WARN_IMAGE) return { bytes, ext };
    const src = join(work, `in-${n}${ext}`);
    writeFileSync(src, bytes);
    // JPEG has no transparency (cut-outs would turn black), so images with alpha become WebP.
    const pixFmt = spawnSync('ffprobe', ['-v', 'error', '-select_streams', 'v', '-show_entries', 'stream=pix_fmt', '-of', 'csv=p=0', src], { encoding: 'utf8' }).stdout.trim();
    const alpha = /a/.test(pixFmt.replace(/^(gray|pal)/, '')) || pixFmt === 'pal8';
    const outExt = alpha ? '.webp' : '.jpg';
    const out = join(work, `out-${n}${outExt}`);
    const quality = alpha ? ['-c:v', 'libwebp', '-quality', '82'] : ['-q:v', '4'];
    ffmpeg(['-i', src, '-map_metadata', '-1', '-vf', "scale='min(1280,iw)':-2:flags=lanczos", ...quality, out], `Clue ${n}`);
    const small = readFileSync(out);
    return small.length < bytes.length ? { bytes: small, ext: outExt } : { bytes, ext };
}

/** Any video or GIF → silent, metadata-free H.264 MP4 that every phone plays inline. */
function encodeVideo(bytes, ext, trim, n, generated = false) {
    const src = join(work, `in-${n}${ext}`);
    const out = join(work, `clip-${n}.mp4`);
    writeFileSync(src, bytes);
    const span = trim ? ['-ss', String(trim.start), '-t', String(trim.end - trim.start)] : [];
    // Generated clips are already H.264 at the right size: keep the picture, drop the sound and metadata.
    const video = generated && !trim
        ? ['-c:v', 'copy']
        : ['-vf', `${BOX},format=yuv420p`, '-c:v', 'libx264', '-preset', 'slow', '-crf', '26', '-profile:v', 'high', '-flags:v', '+bitexact'];
    ffmpeg(
        [...span, '-i', src, '-an', '-sn', '-dn', '-map_metadata', '-1', '-map_chapters', '-1',
            ...video, '-movflags', '+faststart', '-fflags', '+bitexact', '-metadata', 'encoder=', out],
        `Clue ${n}`
    );
    const seconds = probeSeconds(out);
    if (seconds > 12) console.warn(`! Clue ${n} runs ${seconds.toFixed(1)} s. Trim it to the action (3–8 s) with @start-end.`);
    // Contact sheet: 8 evenly spaced frames, for checking the clip before it ships.
    const sheet = join(work, `${id}-${n}-frames.png`);
    ffmpeg(['-i', out, '-vf', `fps=${Math.max(8 / Math.max(seconds, 0.1), 0.01)},scale=320:-2,tile=4x2`, '-frames:v', '1', sheet], `Clue ${n} preview`);
    console.log(`  clue ${n}: ${seconds.toFixed(1)} s video · frames to review: ${sheet}`);
    return readFileSync(out);
}

function postJson(path, body) {
    return new Promise((resolveP, rejectP) => {
        const url = new URL(API + path);
        const payload = JSON.stringify(body);
        const headers = { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(payload) };
        if (process.env.IMAGE_API_KEY) headers.Authorization = `Bearer ${process.env.IMAGE_API_KEY}`;
        // node:http rather than fetch: video generation can block for many minutes, past fetch's header timeout.
        const req = http.request({ hostname: url.hostname, port: url.port, path: url.pathname, method: 'POST', headers }, res => {
            const chunks = [];
            res.on('data', c => chunks.push(c));
            res.on('end', () => {
                const text = Buffer.concat(chunks).toString('utf8');
                let json;
                try {
                    json = JSON.parse(text);
                } catch {
                    return rejectP(new Error(`API ${res.statusCode}: ${text.slice(0, 200)}`));
                }
                if (res.statusCode >= 400) return rejectP(new Error(json.error?.message ?? `API ${res.statusCode}`));
                resolveP(json);
            });
        });
        req.setTimeout(0);
        req.on('error', rejectP);
        req.end(payload);
    });
}

let apiChecked = false;
async function generate(kind, prompt, n) {
    if (!apiChecked) {
        const health = await fetch(`${API}/health`).then(r => r.json()).catch(() => null);
        if (!health) fail(`The image API isn't running at ${API}. Ask the user to start it: open ComfyUI Desktop, then \`uv run serve\` in the imagegen folder.`);
        if (!health.comfyui) fail('The image API is up but ComfyUI is not reachable. Ask the user to open ComfyUI Desktop.');
        apiChecked = true;
    }
    if (leaks(prompt)) console.warn(`! Clue ${n} prompt names the answer. Fine for a subject, but check the result has no text.`);
    const started = Date.now();
    let res;
    try {
        if (kind === 'image') {
            console.log(`  clue ${n}: generating image…`);
            res = await postJson('/v1/images/generations', { prompt: prompt + NO_TEXT, model: 'official', speed: 'lightning', size: `${GEN_SIZE}x${GEN_SIZE}`, response_format: 'url' });
        } else {
            console.log(`  clue ${n}: generating ${videoSeconds} s video${keyframes.length ? ` from ${keyframes.length} keyframe(s)` : ''}… (1–5 min)`);
            // The clip takes keyframe 1's shape, so square every keyframe at 512×512 first.
            const images = await Promise.all(keyframes.map(async (k, j) => {
                const { bytes, ext } = /^https?:\/\//.test(k) ? await download(k, n) : { bytes: readFileSync(resolve(k)), ext: extname(k).toLowerCase() };
                const src = join(work, `key-${j}${ext}`);
                const out = join(work, `key-${j}-square.png`);
                writeFileSync(src, bytes);
                ffmpeg(['-i', src, '-map_metadata', '-1', '-vf', SQUARE, '-frames:v', '1', out], `Keyframe ${j + 1}`);
                return `data:image/png;base64,${readFileSync(out).toString('base64')}`;
            }));
            res = await postJson('/v1/videos/generations', {
                prompt: prompt + ' No on-screen text or captions.',
                model: 'official',
                speed: 'fast',
                duration: videoSeconds,
                resolution: '480p',
                ...(images.length ? { images } : { aspect_ratio: '1:1' }),
                response_format: 'url',
            });
        }
    } catch (e) {
        fail(`Clue ${n} generation failed: ${e.message}`);
    }
    const out = await download(res.data[0].url, n);
    const saved = join(work, `generated-${n}${out.ext}`);
    writeFileSync(saved, out.bytes);
    console.log(`  clue ${n}: generated in ${((Date.now() - started) / 1000).toFixed(0)} s (seed ${res.data[0].seed}) · saved ${saved}`);
    return { ...out, generated: true };
}

// ---- clues ----
const files = [];
const images = [];
for (const [i, raw] of clues.entries()) {
    const n = i + 1;
    let clue = raw;
    let trim = null;
    const span = !/^(text|emoji|gen-image|gen-video):/.test(raw) && raw.match(/^(.*)@(\d+(?:\.\d+)?)-(\d+(?:\.\d+)?)$/);
    if (span) {
        clue = span[1];
        trim = { start: Number(span[2]), end: Number(span[3]) };
        if (!(trim.end > trim.start)) fail(`Clue ${n}: trim end must be after start`);
    }

    let bytes;
    let ext;
    let generated = false;
    if (clue.startsWith('text:')) {
        const text = clue.slice(5).trim();
        if (!text) fail(`Clue ${n} text is empty`);
        if (leaks(text)) fail(`Clue ${n} text gives the answer away: "${text}"`);
        bytes = Buffer.from(textCard(text));
        ext = '.svg';
    } else if (clue.startsWith('emoji:')) {
        const emoji = clue.slice(6).trim();
        if (!emoji) fail(`Clue ${n} emoji is empty`);
        ({ bytes, ext } = await download(`${TWEMOJI}/${twemojiName(emoji)}.svg`, n));
        if (!credits.includes(TWEMOJI_CREDIT)) credits.push(TWEMOJI_CREDIT);
    } else if (clue.startsWith('gen-image:') || clue.startsWith('gen-video:')) {
        const prompt = clue.slice(clue.indexOf(':') + 1).trim();
        if (!prompt) fail(`Clue ${n} prompt is empty`);
        ({ bytes, ext, generated } = await generate(clue.startsWith('gen-image:') ? 'image' : 'video', prompt, n));
    } else if (/^https?:\/\//.test(clue)) {
        ({ bytes, ext } = await download(clue, n));
    } else {
        const src = resolve(clue);
        if (!existsSync(src)) fail(`Clue ${n} not found: ${clue}`);
        ext = extname(src).toLowerCase();
        if (ext === '.jpeg') ext = '.jpg';
        if (!IMAGE_EXT.has(ext) && !VIDEO_EXT.has(ext)) fail(`Clue ${n} is not an image or video (${ext || 'no extension'})`);
        bytes = readFileSync(src);
    }

    if (VIDEO_EXT.has(ext)) {
        bytes = encodeVideo(bytes, ext, trim, n, generated);
        ext = '.mp4';
        if (bytes.length > WARN_VIDEO) console.warn(`! Clue ${n} is ${(bytes.length / 1048576).toFixed(1)} MB. Trim it shorter; every phone downloads it.`);
    } else {
        if (trim) fail(`Clue ${n}: @start-end only applies to videos`);
        ({ bytes, ext } = shrinkImage(stripMetadata(bytes, ext), ext, n));
        const made = /^(text|emoji):/.test(clue);
        if (ext === '.svg' && !made && leaks(bytes.toString('utf8'))) fail(`Clue ${n} SVG contains the answer as text`);
        if (bytes.length > WARN_IMAGE) console.warn(`! Clue ${n} is ${Math.round(bytes.length / 1024)} KB. Prefer a ~1200px-wide version under 400 KB.`);
    }
    const name = `${id}-${n}${ext}`;
    files.push({ name, bytes });
    images.push(`${category}/${name}`);
}

const entry = { id, answer: answer.trim(), accept: accept.map(a => a.trim()).filter(Boolean), images };
if (credits.length) entry.credits = credits.map(c => c.trim()).filter(Boolean);
console.log(JSON.stringify(entry, null, 4));
if (dryRun) {
    console.log(`(dry run: ${files.map(f => `${f.name} ${Math.round(f.bytes.length / 1024)} KB`).join(', ')}; temp files in ${work})`);
    process.exit(0);
}

const outDir = join(root, 'public/games/guess-the', category);
mkdirSync(outDir, { recursive: true });
for (const f of files) writeFileSync(join(outDir, f.name), f.bytes);
data.questions.push(entry);
writeFileSync(file, JSON.stringify(data, null, 4) + '\n');
console.log(`✓ Added ${category}/${id} (${images.length} clue${images.length === 1 ? '' : 's'}). Files in public/games/guess-the/${category}/`);
